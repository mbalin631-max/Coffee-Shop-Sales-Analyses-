--step 1: total each product first, so the category labels use full product totals
with product_totals as (
  select product_detail,
         sum(transaction_qty) as units,--total units sold per product
         sum(transaction_qty*unit_price) as revenue--total revenue per product
  from dataset.coffee.shop
  group by product_detail
)-- this is like a temporary table that SQL creates while the query below runs. It's not saved anywhere.

--step 2: join the product totals to the original dataset, so we can use the totals in our calculations
select store_location,
       product_category,
       product_type,
       s.product_detail,
       dayname(transaction_date) as day_of_week,--classifying dates based on day of week
       monthname(transaction_date) as month_of_year,--classifying months based on month of year
       hour(transaction_time) as hour_of_day,
       --classifying days based on day of week

       case when dayname(transaction_date) in ('Sat','Sun') then 'Weekend'
            else 'Weekday'
       end as day_classification,

       --classifying time based on time of day
       case when hour(transaction_time) between 6 and 11 then 'morning'
            when hour(transaction_time) between 12 and 16 then 'afternoon'
            when hour(transaction_time) between 17 and 21 then 'evening'
            else 'early hours'
       end as time_classification,

       count(transaction_id) as total_transactions,--counting total transactions
       sum(transaction_qty) as total_units_sold,--counting total units sold
       round(sum(transaction_qty*unit_price), 2) as revenue,--counting total revenue
       round(avg(unit_price), 2) as avg_unit_price,--counting average unit price

       --classifying products based on total units sold (uses the product total, not the row)
       case when units >= 4000 then 'best seller'
            when units >= 1000 then 'average seller'
            else 'needs promotion'
       end as popularity,

       --classifying products based on total revenue (uses the product total, not the row)
       case when revenue >= 12000 then 'high revenue product'
            when revenue >= 5000 then 'medium revenue product'
            else 'low revenue product'
       end as revenue_category

from dataset.coffee.shop s
join product_totals p on s.product_detail = p.product_detail--matching each row to its product total


--grouping without transaction_id/date/time, so sums cover many sales, not one
group by store_location,
         product_category,
         product_type,
         s.product_detail,
         dayname(transaction_date),
         monthname(transaction_date),
         hour(transaction_time),
         case when dayname(transaction_date) in ('Sat','Sun') then 'Weekend'
              else 'Weekday' end,
         case when hour(transaction_time) between 6 and 11 then 'morning'
              when hour(transaction_time) between 12 and 16 then 'afternoon'
              when hour(transaction_time) between 17 and 21 then 'evening'
              else 'early hours' end,
         units,
         revenue;
